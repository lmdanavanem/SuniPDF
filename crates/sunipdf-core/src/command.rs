#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Menu {
    File,
    Edit,
    View,
    Pages,
    Forms,
    Security,
    Convert,
    /// Outils du hub « Tous les outils » (entrer dans un outil, le quitter).
    Tools,
    Help,
}

#[derive(Debug)]
pub struct CommandInfo {
    pub command: Command,
    /// Identifiant stable (CLI, automatisation, raccourcis configurables).
    pub id: &'static str,
    /// Clé i18n du libellé.
    pub label_key: &'static str,
    /// Clé i18n du raccourci affiché, s'il existe.
    pub shortcut_key: Option<&'static str>,
    pub needs_document: bool,
    pub menu: Menu,
}

macro_rules! cmd {
    ($c:ident, $id:literal, $label:literal, $shortcut:expr, $doc:literal, $menu:ident) => {
        CommandInfo {
            command: Command::$c,
            id: $id,
            label_key: $label,
            shortcut_key: $shortcut,
            needs_document: $doc,
            menu: Menu::$menu,
        }
    };
}

